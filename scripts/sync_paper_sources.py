#!/usr/bin/env python3
"""Generate the full technical-report chapters from the shared manuscript.

The six files under sections/ are the editable literature chapters.  The report
retains its own abstract, introduction and conclusion under doc/sec/, while
these generated files promote the ACL subsection hierarchy by one level.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
HEADER = "% Generated by scripts/sync_paper_sources.py; edit the corresponding sections/*.tex source.\n"


def read_shared(name):
    text = (ROOT / "sections" / name).read_text(encoding="utf-8")
    # Figure wrappers are shared by the ACL version; inline them so report paths
    # stay relative to doc/ and do not depend on the caller's TeX input path.
    def inline(match):
        return (ROOT / (match[1] + ".tex")).read_text(encoding="utf-8")
    text = re.sub(r"\\input\{(figs_by_qixingyu/[^}]+)\}", inline, text)
    return text.replace("figs_by_qixingyu/", "figs/")


def promoted(source, title, label):
    text = read_shared(source)
    text = re.sub(r"^\\subsection\{[^\n]*\}\s*", "", text, count=1)
    text = text.replace("\\subsubsection", "\\subsection")
    return HEADER + f"\\section{{{title}}}\n\\label{{{label}}}\n\n" + text.rstrip() + "\n"


def main():
    target = ROOT / "doc/sec"
    perception = HEADER + r"""\section{Document Layout Analysis and OCR}
\label{sec:layout_ocr}

Perception constructs the textual and spatial evidence consumed by downstream
document reasoning. Layout analysis and OCR are complementary interfaces, and
their outputs may also be combined with direct visual representations.

""" + read_shared("layout.tex") + "\n\n" + read_shared("ocr.tex")
    outputs = {"2_layout_ocr.tex": perception}
    for source, dest, title, label in (
        ("table.tex", "3_table.tex", "Table Understanding and Question Answering", "sec:table"),
        ("text.tex", "4_text_rag.tex", "Text-Based Retrieval-Augmented Generation", "sec:text_rag"),
        ("multi.tex", "5_vlm.tex", "Vision-Language Models for Document Understanding", "sec:vlm"),
        ("eval.tex", "6_eval.tex", "Evaluation", "sec:eval"),
    ):
        outputs[dest] = promoted(source, title, label)
    for name, text in outputs.items():
        (target / name).write_text(text, encoding="utf-8")
    # Keep the legacy ACL wrapper on the same full manuscript and corrected
    # abstract, instead of maintaining a second divergent introduction/outlook.
    acl_path = ROOT / "acl_latex.tex"
    acl = acl_path.read_text(encoding="utf-8")
    preamble = acl.split(r"\begin{document}", 1)[0]
    abstract = (target / "0_abstract.tex").read_text(encoding="utf-8").strip()
    abstract = abstract[abstract.index("{") + 1:abstract.rfind("}")].lstrip("%\n").strip()
    acl_body = "\n".join(r"\input{doc/sec/" + name + "}" for name in (
        "1_intro", "2_layout_ocr", "3_table", "4_text_rag", "5_vlm", "6_eval", "7_conclusion"
    ))
    report_main = (ROOT / "doc/main.tex").read_text(encoding="utf-8")
    overview = re.search(r"\\begin\{figure\*\}.*?\\label\{fig:pipeline_overview\}.*?\\end\{figure\*\}", report_main, re.S)
    overview_text = overview[0] + "\n\n" if overview else ""
    acl_path.write_text(preamble + r"\begin{document}" + "\n" +
                        "% Generated body: run scripts/sync_paper_sources.py after shared chapter edits.\n" +
                        r"\maketitle" + "\n" + r"\begin{abstract}" + "\n" + abstract + "\n" +
                        r"\end{abstract}" + "\n\n" + overview_text + acl_body + "\n\n" +
                        r"\bibliography{custom}" + "\n" + r"\end{document}" + "\n", encoding="utf-8")
    print("Synchronized full report chapters:", ", ".join(outputs))


if __name__ == "__main__":
    main()
